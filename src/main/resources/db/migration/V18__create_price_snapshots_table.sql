-- 시세 조회 실패 시 되돌려줄 "마지막으로 성공한 조회값"을 보관한다.
--
-- WHY: stale-on-error 폴백(D-058, 릴리즈 체크리스트 "장애 시 마지막 조회값 표시")이
-- 지금까지 PriceService의 메모리 맵에만 있었다. 그래서 외부 시세 서비스가 죽어 있는
-- 동안 백엔드를 재기동하면 폴백할 값이 통째로 사라져 화면 전체가 "시세 조회 실패"가 됐다.
-- 장애 대응 장치가 정작 장애 중 배포·재시작에 무력화되는 구조였다.
--
-- 이 테이블은 D-050(파생값 캐싱 테이블 금지)이 막는 대상이 아니다. D-050은 transactions
-- 에서 계산되는 수량/평단/손익률을 말하고, 시세는 우리 데이터에서 파생되는 값이 아니라
-- 외부에서 관측한 원본 값이다. 계산·추정·보간도 하지 않는다 — 받은 값을 그대로 적어둘 뿐이다.
CREATE TABLE price_snapshots (
    -- "CATEGORY:SYMBOL" 형태의 조회 키. PriceService의 메모리 캐시 키와 같은 형식이라
    -- 두 층이 같은 키로 움직인다.
    price_key   VARCHAR(80)     PRIMARY KEY,
    price       NUMERIC(18, 8)  NOT NULL,
    -- 이 값을 외부 API에서 실제로 받아온 시각. 화면이 "언제 시세인지"를 밝히는 근거라
    -- 반드시 함께 저장한다(시세 기준일을 항상 밝힌다는 표시 규칙).
    fetched_at  TIMESTAMP       NOT NULL
);
